#!/usr/bin/env python3
"""Build the GPS narration master and align captions to the user-selected voice.

The speech audio is generated separately with Arena's speech tool using ONLY
voice-00, the Indian-English male narration voice selected by the user. This
script never chooses or synthesizes a voice. It paces that single full-script
take, then derives caption/scene/SFX timing from verified ASR word timestamps.

Commands (run with an environment providing numpy and soundfile):
  python tools/gen_gps_ai_speech.py master
  python tools/gen_gps_ai_speech.py align

FFMPEG_BIN may point to an FFmpeg binary. The align step expects
shorts/short-14-gps-explainer/transcription-voice-00.json from faster-whisper.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
SHORT_ID = "short-14-gps-explainer"
SHORT_ROOT = ROOT / "shorts" / SHORT_ID
WORK = SHORT_ROOT / "output" / "ai-speech"
PUBLIC = ROOT / "media" / "voiceovers" / "gps-explainer"
RAW = WORK / "voice-00-full-raw.wav"
TRIMMED = WORK / "voice-00-trimmed-48k.wav"
PACED = WORK / "voice-00-paced-48k.wav"
MASTER_METADATA = WORK / "master.json"
NARRATION = PUBLIC / "narration.wav"
ASR = SHORT_ROOT / "transcription-voice-00.json"
VOICE_ID = "voice-00"
SAMPLE_RATE = 48000
DURATION_S = 60.0
INITIAL_SILENCE_S = 0.65
TARGET_VOICE_END_S = 52.3
FFMPEG = os.environ.get(
    "FFMPEG_BIN",
    "/tmp/arena-ffmpeg/ffmpeg-linux-x86_64-v7.0.2"
    if Path("/tmp/arena-ffmpeg/ffmpeg-linux-x86_64-v7.0.2").is_file()
    else "ffmpeg",
)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(command: list[str]) -> None:
    subprocess.run(command, check=True)


def audio_duration(path: Path) -> float:
    info = sf.info(str(path))
    return info.frames / info.samplerate


def js_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def normalize_tokens(text: str) -> list[str]:
    """Normalize harmless ASR spelling/number differences, not wording."""
    text = text.lower().replace("g p s", "gps")
    text = text.replace("kilometres", "kilometers").replace("kilometre", "kilometer")
    text = text.replace("tri-lateration", "trilateration")
    compact = re.sub(r"[\s,]+", "", text).strip(".")
    if compact == "20000":
        return ["twenty", "thousand"]
    if compact in {"20000km", "20000kilometers"}:
        return ["twenty", "thousand", "kilometers"]
    tokens = re.findall(r"[a-z0-9]+", text.replace("'", ""))
    aliases = {
        "20": "twenty",
        "000": "thousand",
        "km": "kilometers",
        "gps's": "gps",
    }
    return [aliases.get(token, token) for token in tokens]


def write_ts_module(timed: list[dict], scenes: list[dict], cues: list[dict]) -> None:
    vo_rows = [
        "  { id: %s, scene: %s, text: %s, start: %.3f, end: %.3f },"
        % (js_string(x["id"]), js_string(x["scene"]), js_string(x["text"]), x["start"], x["end"])
        for x in timed
    ]
    scene_rows = [
        "  { id: %s, title: %s, start: %.3f, end: %.3f },"
        % (js_string(x["id"]), js_string(x["title"]), x["start"], x["end"])
        for x in scenes
    ]
    cue_rows = [
        "  { at: %.3f, id: %s, gain: %.6f },"
        % (x["at_s"], js_string(x["sfx_id"]), 10 ** (x["gain_db"] / 20))
        for x in cues
    ]
    path = ROOT / "remotion" / "src" / "shots" / "short-14" / "vo.gen.ts"
    path.write_text(
        "// Generated by tools/gen_gps_ai_speech.py.\n"
        "// Single user-selected voice-00 take; verified ASR word-timestamp alignment.\n\n"
        "export type GpsLine = { id: string; scene: string; text: string; start: number; end: number };\n"
        "export type GpsScene = { id: string; title: string; start: number; end: number };\n\n"
        "export const VO: GpsLine[] = [\n" + "\n".join(vo_rows) + "\n];\n\n"
        "export const SCENES: GpsScene[] = [\n" + "\n".join(scene_rows) + "\n];\n\n"
        "export const SFX_CUES: { at: number; id: string; gain: number }[] = [\n"
        + "\n".join(cue_rows) + "\n];\n"
    )


def master() -> None:
    WORK.mkdir(parents=True, exist_ok=True)
    PUBLIC.mkdir(parents=True, exist_ok=True)
    if not RAW.is_file():
        raise SystemExit(f"Missing selected-voice take: {RAW}")
    if sf.info(str(RAW)).samplerate != 24000:
        raise SystemExit("Expected the selected speech tool's 24 kHz WAV")

    run([
        FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-i", str(RAW),
        "-af", "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.05,"
               "areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.12,"
               "areverse,aresample=48000",
        "-ar", "48000", "-ac", "1", "-c:a", "pcm_s16le", str(TRIMMED),
    ])
    trimmed_duration = audio_duration(TRIMMED)
    tempo_rate = trimmed_duration / (TARGET_VOICE_END_S - INITIAL_SILENCE_S)
    if not 0.85 <= tempo_rate <= 1.30:
        raise SystemExit(f"Pacing would be unnatural: {tempo_rate:.4f}x")
    run([
        FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-i", str(TRIMMED),
        "-af", f"atempo={tempo_rate:.9f}",
        "-ar", "48000", "-ac", "1", "-c:a", "pcm_f32le", str(PACED),
    ])
    paced, sample_rate = sf.read(PACED, dtype="float32")
    if sample_rate != SAMPLE_RATE:
        raise SystemExit("Unexpected paced sample rate")
    master_audio = np.zeros(round(DURATION_S * SAMPLE_RATE), dtype=np.float32)
    start = round(INITIAL_SILENCE_S * SAMPLE_RATE)
    end = start + len(paced)
    if end > master_audio.size:
        raise SystemExit("Selected-voice narration exceeds 60 seconds")
    master_audio[start:end] = paced
    sf.write(NARRATION, master_audio, SAMPLE_RATE, subtype="PCM_16")
    metadata = {
        "voice_id": VOICE_ID,
        "voice_selection": "User-selected Indian-English male narration voice; no alternate voice used",
        "take": "One continuous full-script take",
        "raw_file": str(RAW.relative_to(ROOT)),
        "raw_sha256": sha256(RAW),
        "raw_duration_seconds": round(audio_duration(RAW), 6),
        "trimmed_duration_seconds": round(trimmed_duration, 6),
        "tempo_rate": round(tempo_rate, 9),
        "tempo_algorithm": "FFmpeg atempo WSOLA; pitch preserved; same rate for the entire take",
        "initial_silence_seconds": INITIAL_SILENCE_S,
        "narration_file": str(NARRATION.relative_to(ROOT)),
        "narration_sha256": sha256(NARRATION),
        "narration_duration_seconds": audio_duration(NARRATION),
        "paced_speech_end_seconds": round(end / SAMPLE_RATE, 6),
    }
    MASTER_METADATA.write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps(metadata, indent=2))


def align() -> None:
    metadata = json.loads(MASTER_METADATA.read_text())
    if metadata["voice_id"] != VOICE_ID:
        raise SystemExit("Voice ID mismatch; refusing to change the selected voice")
    if sha256(NARRATION) != metadata["narration_sha256"]:
        raise SystemExit("Narration changed after mastering")
    result = json.loads(ASR.read_text())
    if result["audio_sha256"] != metadata["narration_sha256"]:
        raise SystemExit("ASR does not belong to the selected-voice narration master")

    beats = json.loads((SHORT_ROOT / "beats.json").read_text())
    old_by_id = {item["id"]: item for item in beats["vo"]}
    plan = json.loads((SHORT_ROOT / "sfx-plan.json").read_text())
    segments = beats["vo"]
    expected_flat = []
    for index, segment in enumerate(segments):
        expected_flat.extend((index, token) for token in normalize_tokens(segment["text"]))
    words = [word for segment in result["segments"] for word in segment.get("words", [])]
    asr_alignment = [(token, word) for word in words for token in normalize_tokens(word["word"])]
    asr_tokens = [token for token, _ in asr_alignment]
    expected_tokens = [token for _, token in expected_flat]
    if expected_tokens != asr_tokens:
        mismatch = next(
            (i for i, pair in enumerate(zip(expected_tokens, asr_tokens)) if pair[0] != pair[1]),
            min(len(expected_tokens), len(asr_tokens)),
        )
        raise SystemExit(
            "Normalized script/ASR mismatch at token "
            f"{mismatch}: expected={expected_tokens[mismatch:mismatch+8]} "
            f"asr={asr_tokens[mismatch:mismatch+8]}; "
            f"lengths={len(expected_tokens)}/{len(asr_tokens)}"
        )
    timed = []
    cursor = 0
    for index, segment in enumerate(segments):
        count = len(normalize_tokens(segment["text"]))
        if count == 0:
            raise SystemExit(f"No words in {segment['id']}")
        segment_alignment = asr_alignment[cursor:cursor + count]
        cursor += count
        start = max(INITIAL_SILENCE_S, float(segment_alignment[0][1]["start"]))
        end = float(segment_alignment[-1][1]["end"])
        timed.append({
            "id": segment["id"],
            "scene": segment["scene"],
            "text": segment["text"],
            "speak": segment.get("speak", segment["text"]),
            "start": round(start, 3),
            "end": round(end, 3),
            "duration": round(end - start, 3),
        })
    if cursor != len(asr_alignment):
        raise SystemExit("Not all ASR tokens were aligned")
    voice_end = timed[-1]["end"]
    if voice_end > 58.4:
        raise SystemExit(f"Narration ends too late for the outro: {voice_end}")

    scene_defs = [(item["id"], item["title"]) for item in beats["scenes"]]
    scenes = []
    for index, (scene_id, title) in enumerate(scene_defs):
        members = [item for item in timed if item["scene"] == scene_id]
        start = 0.0 if index == 0 else max(0.0, members[0]["start"] - 0.35)
        scenes.append({"id": scene_id, "title": title, "start": round(start, 3), "end": None})
    for index in range(len(scenes) - 1):
        scenes[index]["end"] = scenes[index + 1]["start"]
    scenes[-1]["end"] = DURATION_S

    cues = []
    by_id = {item["id"]: item for item in timed}
    for event in plan["events"]:
        source = event["sync_source"]
        old_offset = event["at_s"] - old_by_id[source]["start"]
        cues.append({
            "at_s": round(max(0.0, by_id[source]["start"] + old_offset), 3),
            "sfx_id": event["sfx_id"],
            "gain_db": event["gain_db"],
            "cue": event["cue"],
            "sync_source": source,
        })

    new_beats = {
        "id": SHORT_ID,
        "title": "How GPS Finds You",
        "composition": "Short14GpsExplainer",
        "format": {"width": 1080, "height": 1920, "fps": 30, "durationSec": DURATION_S},
        "voiceStatus": "ai-speech:voice-00:user-selected-indian-male:complete",
        "aiSpeech": {
            **metadata,
            "alignment": f"{result['engine']} {result['model']} word timestamps on the exact paced narration master",
            "normalized_script_match": True,
            "mean_word_probability": result["mean_word_probability"],
        },
        "gaps": {
            "initial": INITIAL_SILENCE_S,
            "pauses": "Natural pauses from one continuous take, preserved under the same tempo adjustment",
        },
        "voiceEnd": voice_end,
        "scenes": scenes,
        "vo": timed,
    }
    (SHORT_ROOT / "beats.json").write_text(json.dumps(new_beats, indent=2) + "\n")
    new_plan = {
        "master": f"shorts/{SHORT_ID}/output/how-gps-finds-you.mp4",
        "master_fps": 30,
        "catalog": "media/library/sfx/catalog.json",
        "music": {
            "id": "tech-pulse",
            "file": "media/library/music/clips/tech-pulse.mp3",
            "ducked_under_narration": True,
        },
        "render": {
            "composition": "remotion/out/Short14GpsExplainer.mp4",
            "out": f"shorts/{SHORT_ID}/output/how-gps-finds-you.mp4",
            "end_s": DURATION_S,
        },
        "note": "All cues use verified word-timestamp alignment from one continuous user-selected voice-00 narration take.",
        "events": cues,
    }
    (SHORT_ROOT / "sfx-plan.json").write_text(json.dumps(new_plan, indent=2) + "\n")
    write_ts_module(timed, scenes, cues)
    print(f"Aligned {len(timed)} captions and {len(cues)} cues; voice end={voice_end:.3f}s")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["master", "align"])
    args = parser.parse_args()
    if args.command == "master":
        master()
    else:
        align()
