#!/usr/bin/env python3
"""Master and align five calm explainers using only user-selected voice-00.

Speech is generated separately with Arena's speech tool as one continuous take
per project. This script never selects or synthesizes a voice and never speeds
up a source take. Captions/scenes/SFX are written only after exact ASR alignment.

  FFMPEG_BIN=/path/to/ffmpeg python tools/gen_next_five_ai_speech.py master
  python tools/gen_next_five_ai_speech.py align
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
CONFIG = json.loads((ROOT / "tools" / "next-five-projects.json").read_text())
DEFAULTS = CONFIG["defaults"]
PROJECTS = CONFIG["projects"]
VOICE_ID = "voice-00"
SAMPLE_RATE = 48000
FFMPEG = os.environ.get("FFMPEG_BIN", "ffmpeg")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(command: list[str]) -> None:
    subprocess.run(command, check=True)


def audio_duration(path: Path) -> float:
    info = sf.info(str(path))
    return info.frames / info.samplerate


def js_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def normalize_tokens(text: str) -> list[str]:
    """Normalize harmless ASR spelling/spacing differences, not wording."""
    text = text.lower().replace("’", "'")
    text = re.sub(r"\bq[.\s-]*r\b", "qr", text)
    text = text.replace("photo sites", "photosites").replace("photo site", "photosite")
    text = re.sub(r"\bde[- ]mosaicing\b", "demosaicing", text)
    tokens = re.findall(r"[a-z0-9]+", text.replace("'", ""))
    aliases = {"0": "zero", "1": "one", "canceling": "cancelling"}
    return [aliases.get(token, token) for token in tokens]


def paths_for(project: dict) -> dict:
    short_root = ROOT / "shorts" / project["id"]
    work = short_root / "output" / "ai-speech"
    return {
        "short_root": short_root,
        "work": work,
        "raw": work / "voice-00-full-raw.wav",
        "trimmed": work / "voice-00-trimmed-48k.wav",
        "paced": work / "voice-00-paced-48k.wav",
        "metadata": work / "master.json",
        "asr": short_root / "transcription-voice-00.json",
        "narration": ROOT / "media" / "voiceovers" / project["slug"] / "narration.wav",
    }


def write_ts_module(project: dict, timed: list[dict], scenes: list[dict], cues: list[dict]) -> None:
    vo_rows = [
        "  { id: %s, scene: %s, text: %s, start: %.3f, end: %.3f },"
        % (js_string(x["id"]), js_string(x["scene"]), js_string(x["text"]), x["start"], x["end"])
        for x in timed
    ]
    scene_rows = [
        "  { id: %s, title: %s, start: %.3f, end: %.3f },"
        % (js_string(x["id"]), js_string(x["title"]), x["start"], x["end"])
        for x in scenes
    ]
    cue_rows = [
        "  { at: %.3f, id: %s, gain: %.6f },"
        % (x["at_s"], js_string(x["sfx_id"]), 10 ** (x["gain_db"] / 20))
        for x in cues
    ]
    shot_number = project["id"].split("-")[1]
    path = ROOT / "remotion" / "src" / "shots" / f"short-{shot_number}" / "vo.gen.ts"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "// Generated by tools/gen_next_five_ai_speech.py.\n"
        "// One continuous user-selected voice-00 take; verified ASR alignment.\n\n"
        "export type NextLine = { id: string; scene: string; text: string; start: number; end: number };\n"
        "export type NextScene = { id: string; title: string; start: number; end: number };\n\n"
        "export const VO: NextLine[] = [\n" + "\n".join(vo_rows) + "\n];\n\n"
        "export const SCENES: NextScene[] = [\n" + "\n".join(scene_rows) + "\n];\n\n"
        "export const SFX_CUES: { at: number; id: string; gain: number }[] = [\n"
        + "\n".join(cue_rows) + "\n];\n"
    )


def master_one(project: dict) -> dict:
    paths = paths_for(project)
    paths["work"].mkdir(parents=True, exist_ok=True)
    paths["narration"].parent.mkdir(parents=True, exist_ok=True)
    raw = paths["raw"]
    if not raw.is_file():
        raise SystemExit(f"Missing selected-voice take: {raw}")
    if sf.info(str(raw)).samplerate != 24000:
        raise SystemExit(f"Expected 24 kHz selected-voice WAV: {raw}")

    run([
        FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-i", str(raw),
        "-af", "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08,"
               "areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.15,"
               "areverse,aresample=48000",
        "-ar", "48000", "-ac", "1", "-c:a", "pcm_s16le", str(paths["trimmed"]),
    ])
    trimmed_duration = audio_duration(paths["trimmed"])
    target_voice_end = float(project.get("target_voice_end_s", DEFAULTS["target_voice_end_s"]))
    requested_rate = trimmed_duration / (target_voice_end - DEFAULTS["initial_silence_s"])
    tempo_rate = min(1.0, requested_rate)
    if not 0.84 <= tempo_rate <= 1.0:
        raise SystemExit(f"Pacing would be unnatural for {project['id']}: {tempo_rate:.4f}x")
    run([
        FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-i", str(paths["trimmed"]),
        "-af", f"atempo={tempo_rate:.9f}",
        "-ar", "48000", "-ac", "1", "-c:a", "pcm_f32le", str(paths["paced"]),
    ])
    paced, sample_rate = sf.read(paths["paced"], dtype="float32")
    if sample_rate != SAMPLE_RATE:
        raise SystemExit("Unexpected paced sample rate")
    duration_s = float(project.get("duration_s", DEFAULTS["duration_s"]))
    master_audio = np.zeros(round(duration_s * SAMPLE_RATE), dtype=np.float32)
    start = round(float(DEFAULTS["initial_silence_s"]) * SAMPLE_RATE)
    end = start + len(paced)
    if end > master_audio.size:
        raise SystemExit(f"Narration exceeds {duration_s}s for {project['id']}")
    master_audio[start:end] = paced
    sf.write(paths["narration"], master_audio, SAMPLE_RATE, subtype="PCM_16")
    script = " ".join(line["text"] for line in project["lines"])
    metadata = {
        "voice_id": VOICE_ID,
        "voice_selection": "User-selected narration voice; one continuous take; no alternate voice used",
        "take": "One continuous full-script take",
        "raw_file": str(raw.relative_to(ROOT)),
        "raw_sha256": sha256(raw),
        "raw_duration_seconds": round(audio_duration(raw), 6),
        "trimmed_duration_seconds": round(trimmed_duration, 6),
        "tempo_rate": round(tempo_rate, 9),
        "requested_tempo_rate": round(requested_rate, 9),
        "tempo_algorithm": "FFmpeg atempo WSOLA; pitch preserved; never faster than source",
        "initial_silence_seconds": DEFAULTS["initial_silence_s"],
        "target_voice_end_seconds": target_voice_end,
        "narration_file": str(paths["narration"].relative_to(ROOT)),
        "narration_sha256": sha256(paths["narration"]),
        "narration_duration_seconds": audio_duration(paths["narration"]),
        "paced_speech_end_seconds": round(end / SAMPLE_RATE, 6),
        "script_sha256": hashlib.sha256(script.encode()).hexdigest(),
        "spoken_words": len(normalize_tokens(script)),
    }
    paths["metadata"].write_text(json.dumps(metadata, indent=2) + "\n")
    return metadata


def align_one(project: dict) -> None:
    paths = paths_for(project)
    duration_s = float(project.get("duration_s", DEFAULTS["duration_s"]))
    metadata = json.loads(paths["metadata"].read_text())
    if metadata["voice_id"] != VOICE_ID:
        raise SystemExit(f"Voice ID mismatch for {project['id']}")
    if sha256(paths["narration"]) != metadata["narration_sha256"]:
        raise SystemExit(f"Narration changed after mastering: {project['id']}")
    result = json.loads(paths["asr"].read_text())
    if result.get("voice_id") != VOICE_ID or result["audio_sha256"] != metadata["narration_sha256"]:
        raise SystemExit(f"ASR does not belong to selected-voice master: {project['id']}")

    expected_flat = []
    for index, segment in enumerate(project["lines"]):
        expected_flat.extend((index, token) for token in normalize_tokens(segment["text"]))
    all_words = [word for segment in result["segments"] for word in segment.get("words", [])]
    speech_end = float(metadata["paced_speech_end_seconds"])
    timed_words = [word for word in all_words if float(word["start"]) < speech_end]
    ignored_tail_words = [word for word in all_words if float(word["start"]) >= speech_end]
    # A tiny low-confidence ASR artifact may be removed only because the full
    # remaining token sequence must still match every scripted word exactly.
    ignored_spurious_words = [
        word for word in timed_words
        if float(word["probability"]) < 0.20 and float(word["end"]) - float(word["start"]) <= 0.10
    ]
    ignored_spurious_ids = {id(word) for word in ignored_spurious_words}
    words = [word for word in timed_words if id(word) not in ignored_spurious_ids]
    asr_alignment = [(token, word) for word in words for token in normalize_tokens(word["word"])]
    asr_tokens = [token for token, _ in asr_alignment]
    expected_tokens = [token for _, token in expected_flat]
    if expected_tokens != asr_tokens:
        mismatch = next(
            (i for i, pair in enumerate(zip(expected_tokens, asr_tokens)) if pair[0] != pair[1]),
            min(len(expected_tokens), len(asr_tokens)),
        )
        raise SystemExit(
            f"{project['id']} normalized script/ASR mismatch at token {mismatch}: "
            f"expected={expected_tokens[mismatch:mismatch+8]} asr={asr_tokens[mismatch:mismatch+8]}; "
            f"lengths={len(expected_tokens)}/{len(asr_tokens)}"
        )

    timed = []
    cursor = 0
    for segment in project["lines"]:
        count = len(normalize_tokens(segment["text"]))
        segment_alignment = asr_alignment[cursor:cursor + count]
        cursor += count
        start = max(float(DEFAULTS["initial_silence_s"]), float(segment_alignment[0][1]["start"]))
        end = float(segment_alignment[-1][1]["end"])
        timed.append({
            **segment, "speak": segment["text"], "start": round(start, 3),
            "end": round(end, 3), "duration": round(end - start, 3),
        })
    if cursor != len(asr_alignment):
        raise SystemExit(f"Not all ASR tokens aligned for {project['id']}")
    voice_end = timed[-1]["end"]
    if voice_end > duration_s - 2.5:
        raise SystemExit(f"Narration ends too late for calm outro: {project['id']} {voice_end}")

    scenes = []
    for index, (scene_id, title) in enumerate(project["scenes"]):
        members = [item for item in timed if item["scene"] == scene_id]
        start = 0.0 if index == 0 else max(0.0, members[0]["start"] - 0.5)
        scenes.append({"id": scene_id, "title": title, "start": round(start, 3), "end": None})
    for index in range(len(scenes) - 1):
        scenes[index]["end"] = scenes[index + 1]["start"]
    scenes[-1]["end"] = duration_s

    by_id = {item["id"]: item for item in timed}
    cues = [{
        "at_s": round(max(0.0, by_id[event["sync_source"]]["start"] + event["offset_s"]), 3),
        "sfx_id": event["sfx_id"], "gain_db": event["gain_db"], "cue": event["cue"],
        "sync_source": event["sync_source"],
    } for event in project["cues"]]
    new_beats = {
        "id": project["id"], "title": project["title"], "composition": project["composition"],
        "format": {
            "width": DEFAULTS["width"], "height": DEFAULTS["height"],
            "fps": DEFAULTS["fps"], "durationSec": duration_s,
        },
        "voiceStatus": "ai-speech:voice-00:user-selected:complete",
        "aiSpeech": {
            **metadata,
            "alignment": f"{result['engine']} {result['model']} word timestamps on exact paced narration master",
            "normalized_script_match": True,
            "mean_word_probability": result["mean_word_probability"],
            "asr_tail_filter": f"Excluded {len(ignored_tail_words)} ASR tokens beginning in digital silence at or after {speech_end:.6f}s",
            "asr_spurious_token_filter": f"Excluded {len(ignored_spurious_words)} ASR tokens lasting <=0.10s with probability <0.20; exact full-script match still required",
        },
        "pacing": f"Calm {duration_s:g}-second explainer; source never sped up; no caption progress line",
        "voiceEnd": voice_end, "scenes": scenes, "vo": timed,
    }
    (paths["short_root"] / "beats.json").write_text(json.dumps(new_beats, indent=2) + "\n")
    new_plan = {
        "master": f"RESULT/{project['result']}", "master_fps": DEFAULTS["fps"],
        "catalog": "media/library/sfx/catalog.json",
        "music": {
            "id": project["music"], "file": f"media/library/music/clips/{project['music']}.mp3",
            "ducked_under_narration": True, "style": "Calm bed, ducked under narration",
        },
        "render": {
            "composition": f"remotion/out/{project['composition']}.mp4",
            "out": f"RESULT/{project['result']}", "end_s": duration_s,
        },
        "note": f"{len(cues)} restrained cues aligned to one continuous user-selected voice-00 narration take.",
        "events": cues,
    }
    (paths["short_root"] / "sfx-plan.json").write_text(json.dumps(new_plan, indent=2) + "\n")
    write_ts_module(project, timed, scenes, cues)
    print(f"{project['id']}: {len(timed)} captions, {len(scenes)} scenes, {len(cues)} cues; voice end={voice_end:.3f}s; tempo={metadata['tempo_rate']:.6f}x")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["master", "align"])
    args = parser.parse_args()
    if args.command == "master":
        for project in PROJECTS:
            metadata = master_one(project)
            print(
                f"{project['id']}: raw={metadata['raw_duration_seconds']:.3f}s; "
                f"tempo={metadata['tempo_rate']:.9f}x; speech end={metadata['paced_speech_end_seconds']:.6f}s; "
                f"sha256={metadata['narration_sha256']}"
            )
    else:
        for project in PROJECTS:
            align_one(project)


if __name__ == "__main__":
    main()
